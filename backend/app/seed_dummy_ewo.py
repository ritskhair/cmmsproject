"""Create reproducible completed EWO records for dashboard/Pareto testing."""

import argparse
import random
import uuid
from datetime import datetime, timedelta

from sqlalchemy.orm import Session

from app.core.database import SessionLocal
from app.models.equipment import Equipment
from app.models.ewo_request import EwoRequest


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--count", type=int, default=50, help="Number of EWO records to create")
    parser.add_argument("--days", type=int, default=30, help="Date range ending today")
    parser.add_argument("--seed", type=int, default=None, help="Optional random seed for repeatable data")
    return parser.parse_args()


def next_ewo_number(year: int, sequence: int) -> str:
    return f"EWO-{year}-DUMMY-{sequence:04d}"


def create_dummy_ewos(db: Session, count: int, days: int, seed: int | None) -> int:
    if count < 1:
        raise ValueError("count must be at least 1")
    if days < 1:
        raise ValueError("days must be at least 1")

    equipment = db.query(Equipment).order_by(Equipment.section, Equipment.asset_id).all()
    if not equipment:
        raise RuntimeError("No equipment exists. Import or create equipment before seeding EWO data.")

    rng = random.Random(seed)
    equipment_by_section: dict[str, list[Equipment]] = {}
    for machine in equipment:
        equipment_by_section.setdefault(machine.section, []).append(machine)
    available_sections = sorted(equipment_by_section)
    now = datetime.utcnow()
    first_date = now - timedelta(days=days - 1)
    sequence = 1
    created = 0

    while db.query(EwoRequest).filter(
        EwoRequest.ewo_number == next_ewo_number(now.year, sequence)
    ).first():
        sequence += 1

    for _ in range(count):
        selected_section = rng.choice(available_sections)
        machine = rng.choice(equipment_by_section[selected_section])
        created_at = first_date + timedelta(
            seconds=rng.randint(0, max(0, int((now - first_date).total_seconds())))
        )
        ewo = EwoRequest(
            id=uuid.uuid4(),
            ewo_number=next_ewo_number(now.year, sequence),
            requestor_name=f"Dummy Operator {rng.randint(1, 20):02d}",
            department="Engineering",
            section=machine.section,
            equipment_id=machine.id,
            component_id=None,
            component_other_description="Generated Pareto test data",
            shift=rng.choice(["Shift 1", "Shift 2", "Shift 3"]),
            team_leader_name=f"Dummy Leader {rng.randint(1, 5):02d}",
            failure_type=rng.choice(["total", "partial"]),
            failure_category=rng.choice(["electrical", "mechanical"]),
            task_list="Investigate and repair simulated failure",
            special_note="Generated by seed_dummy_ewo.py",
            status="completed",
            created_at=created_at,
        )
        db.add(ewo)
        sequence += 1
        created += 1

    db.commit()
    return created


def main() -> None:
    args = parse_args()
    with SessionLocal() as db:
        created = create_dummy_ewos(db, args.count, args.days, args.seed)
    print(f"Created {created} completed dummy EWO records across existing equipment sections.")


if __name__ == "__main__":
    main()
